/**
 * Orte für den Würfel am Szenario-Feld „Ort" – **je Genre eine eigene Liste zu
 * 100 Einträgen**.
 *
 * Aufgebaut wie `backgrounds.ts` und aus demselben Grund nach Genre getrennt
 * statt markiert: ein Ort trägt sein Genre in sich. „Ein Wohnblock, dessen
 * Aufzug seit Jahren steht" und „ein Turm, in dem die Treppe endet, bevor sie
 * oben ankommt" beschreiben dieselbe Enge – aber in Bildern, die sich nicht
 * austauschen lassen.
 *
 * Rein lokal, ohne API, wie alle Würfel im Projekt.
 *
 * **Ein Eintrag ist ein vollständiger Ort, kein Baustein.** Anders als beim
 * Aussehen oder Hintergrund wird hier **nicht** kombiniert: ein Szenario spielt
 * an einem Ort, nicht an zweieinhalb. Deshalb zieht `randomPlace` genau einen.
 *
 * Jeder Eintrag nennt den Ort **und ein Detail, das ihn kippen lässt** – etwas
 * Kaputtes, Verschwiegenes oder Unfertiges. Ein Ort ohne Riss ist eine Kulisse;
 * einer mit Riss ist ein Anfang.
 */


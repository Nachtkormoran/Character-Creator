/**
 * Orte für den Würfel am Szenario-Feld „Ort" – **je Genre eine eigene Liste zu
 * 100 Einträgen**.
 *
 * Aufgebaut wie `backgrounds.ts` und aus demselben Grund nach Genre getrennt
 * statt markiert: ein Ort trägt sein Genre in sich. „Ein Wohnblock, dessen
 * Aufzug seit Jahren steht" und „ein Turm, in dem die Treppe endet, bevor sie
 * oben ankommt" beschreiben dieselbe Enge – aber in Bildern, die sich nicht
 * austauschen lassen.
 *
 * Rein lokal, ohne API, wie alle Würfel im Projekt.
 *
 * Jeder Eintrag nennt den Ort **und ein Detail, das ihn kippen lässt** – etwas
 * Kaputtes, Verschwiegenes oder Unfertiges. Ein Ort ohne Riss ist eine Kulisse;
 * einer mit Riss ist ein Anfang.
 *
 * **Zwei Ebenen je Genre.** Hier stand einmal: „Ein Eintrag ist ein
 * vollständiger Ort, kein Baustein … ein Szenario spielt an einem Ort, nicht an
 * zweieinhalb." Das galt, solange das Feld einen Schauplatz aufnahm. Inzwischen
 * beschreibt es ein **Gebiet mit mehreren Orten darin** – eine Geschichte
 * spielt selten an einem einzigen Punkt –, und dafür braucht der Würfel die
 * Unterscheidung:
 *
 * - `*_AREAS` – **Rahmen**: worin gespielt wird. Stadt, Landstrich, Siedlung,
 *   Station. Die Antwort auf „wo spielt das?".
 * - `*_SPOTS` – **Schauplätze**: Orte *darin*, an denen sich fremde Leben
 *   kreuzen. Arbeitsplätze, Einrichtungen, Wege, Werkstätten.
 *
 * `*_PLACES` bleibt als Zusammenfassung beider bestehen, damit nichts bricht,
 * was die ganze Liste will (etwa die Formbeispiele in `scenarioSamples.ts`).
 *
 * Die Teilung ist **keine neue Textarbeit**, sondern die Gliederung, die in
 * diesen Listen von Anfang an als Rubrik-Kommentar stand („Stadt", „Provinz &
 * Land" gegen „Arbeitsplätze", „Einrichtungen"). Sie ist damit auch nur so
 * genau wie diese Rubriken: Ein einzelner Eintrag kann auf der falschen Ebene
 * sitzen. Für den Würfel reicht das – er ist ein Anfang, kein Ergebnis.
 */


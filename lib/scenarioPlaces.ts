export const PLACES_BY_GENRE: Record<string, string[]> = {
  gegenwart: GEGENWART_PLACES,
  fantasy: FANTASY_PLACES,
  steampunk: STEAMPUNK_PLACES,
  cyberpunk: CYBERPUNK_PLACES,
  historisch: HISTORISCH_PLACES,
  western: WESTERN_PLACES,
};

/**
 * Ein Ort, passend zum Genre. Ohne bekanntes Genre fällt die Wahl auf
 * „Gegenwart" – dieselbe Regel wie in `backgrounds.ts`, und aus demselben
 * Grund wird **nie** über die Listen gemischt.
 */
export function randomPlace(genre?: string): string {
  const pool = PLACES_BY_GENRE[genre ?? ""] ?? GEGENWART_PLACES;
  return pool[Math.floor(Math.random() * pool.length)];
}

/**
 * Ein Ort, passend zum Genre. Ohne bekanntes Genre fällt die Wahl auf
 * „Gegenwart" – dieselbe Regel wie in `backgrounds.ts`, und aus demselben
 * Grund wird **nie** über die Listen gemischt.
 *
 * `ergaenzen` unterscheidet die beiden Lagen, in denen der Knopf gedrückt wird:
 *
 * - **Leeres Feld** (`false`): ein Rahmen und zwei Schauplätze darin,
 *   untereinander. Das ist die Form, die das Feld inzwischen erwartet.
 * - **Gefülltes Feld** (`true`): **nur ein Schauplatz**, den die aufrufende
 *   Seite anhängt. Die Annahme dahinter: Was Leute selbst eintippen, ist der
 *   Rahmen („Berlin", „Ein Fischerdorf"); was ihnen fehlt, ist das Konkrete
 *   darin. Ein zweiter Rahmen wäre in einem Feld, das schon einen hat, fast
 *   immer falsch.
 *
 * Was der Würfel **nicht** kann: prüfen, ob der gezogene Schauplatz zum
 * vorhandenen Rahmen passt. Er liest nicht, was dasteht – „Berlin" und ein
 * Dorfgasthof können nebeneinander landen. Dafür gibt es den KI-Knopf; dieser
 * hier ist der kostenlose, beliebig oft drückbare Anfang.
 */
export function randomPlace(genre?: string, ergaenzen = false): string {
  const key = genre ?? "";
  const spots = SPOTS_BY_GENRE[key] ?? GEGENWART_SPOTS;
  if (ergaenzen) return spots[Math.floor(Math.random() * spots.length)];

  const areas = AREAS_BY_GENRE[key] ?? GEGENWART_AREAS;
  const rahmen = areas[Math.floor(Math.random() * areas.length)];
  return [rahmen, ...pickSome(spots, 2, 2)].join("\n");
}

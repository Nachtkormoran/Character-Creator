/**
 * Bausteine für den Würfel am Szenario-Feld „Figuren" – **je Genre eine eigene
 * Liste von Rollen und eine von Rissen**, kombinatorisch zu einer Figur
 * zusammengesetzt (Name + Rolle + Riss). Anders als bei Ort und Zeit werden hier
 * also **Bausteine** gemischt, wie bei den Regeln – nur über zwei Ebenen: was
 * eine Figur in dieser Welt **tut** (Rolle) und woran sie **kippt** (Riss).
 *
 * Aus rund 100 Rollen und 100 Rissen je Genre entstehen tausende Figuren; der
 * Name kommt aus `names.ts` (genre-passender Kulturkreis). Eine Figur ist damit
 * ein **Notizzettel**, kein Steckbrief: „Name: was sie tut; woran sie kippt."
 *
 * **Rollen und Risse sind subjektlose Verbalphrasen im Präsens** (wie die
 * Hintergründe in `backgrounds.ts`) – **ohne Pronomen auf die Figur** („er/sie/
 * ihr"). So legen sie **kein Geschlecht** fest und passen zu jedem gezogenen
 * Namen. Ein Riss ist immer ein Riss: etwas Verschwiegenes, Ersehntes,
 * Ungelöstes, an dem sich eine Geschichte entzünden kann – nie bloß ein Beruf.
 *
 * Nach Genre **getrennt und nie gemischt** (dieselbe Regel wie in
 * `backgrounds.ts`): Ein Netrunner gehört nicht ins Märchen. Ohne bekanntes
 * Genre fällt die Wahl auf „Gegenwart".
 */


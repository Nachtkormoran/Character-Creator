/**
 * Setzt **eine** Figur zusammen: ein genre-passender Name (`randomName`, Kultur
 * über das Genre), eine Rolle und ein Riss. Geschlecht „egal" – die Bausteine
 * sind pronomenlos, der Name darf jedes Geschlecht haben.
 *
 * Form: `Name: <Rolle>; <Riss>.` – dasselbe „Name: …"-Muster, das auch das
 * zufällig erzeugte Szenario ins Feld schreibt, damit Würfel und KI sich mischen
 * lassen.
 */
function macheFigur(rolle: string, riss: string, genre?: string): string {
  const name = randomName({ gender: "egal", genre });
  return `${name}: ${rolle}; ${riss}.`;
}

/**
 * Würfelt Figuren fürs Feld „Figuren". Ins **leere** Feld kommen zwei bis drei,
 * beim **Ergänzen** eine weitere – dieselbe Logik wie bei den Regeln, nur über
 * zwei Baustein-Ebenen. Innerhalb eines Wurfs sind Rollen und Risse ohne
 * Wiederholung gezogen (`pickSome`), damit nicht zwei Figuren dasselbe tun.
 *
 * Ohne bekanntes Genre fällt die Wahl auf „Gegenwart"; über die Genre-Listen
 * wird **nie gemischt**.
 */
export function randomFigure(genre?: string, ergaenzen = false): string {
  const rollen = ROLLEN_BY_GENRE[genre ?? ""] ?? GEGENWART_ROLLEN;
  const risse = RISSE_BY_GENRE[genre ?? ""] ?? GEGENWART_RISSE;
  const anzahl = ergaenzen ? 1 : 2 + Math.floor(Math.random() * 2); // 2–3
  const r = pickSome(rollen, anzahl, anzahl);
  const k = pickSome(risse, anzahl, anzahl);
  return r.map((rolle, i) => macheFigur(rolle, k[i], genre)).join("\n");
}
